pub fn print_help() {
    println!("jade — the Jade programming language");
    println!();
    println!("USAGE:");
    println!("  jade <file.jde>               Run a Jade source file");
    println!("  jade <file.jde> -v, --verbose Run and print all variables after execution");
    println!("  jade -h, --help               Show this help message");
}